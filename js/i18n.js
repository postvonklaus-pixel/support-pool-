export const LANG_CODES = Object.keys(LANGS);

let _current = LANGS.de;

export function t(key) {
  return _current[key] ?? LANGS.de[key] ?? key;
}

export function initI18n(lang = 'de') {
  _current = LANGS[lang] || LANGS.de;
  applyToDOM();
}

export async function setLang(lang) {
  if (!LANGS[lang]) return;
  _current = LANGS[lang];
  import('./storage.js').then(m => m.setLang(lang));
  import('./state.js').then(({ setState }) => setState('lang', lang));

  // RTL support
  const dir = LANGS[lang].dir || 'ltr';
  document.documentElement.setAttribute('dir', dir);
  document.documentElement.setAttribute('lang', lang);

  applyToDOM();
  // Re-render active screen
  import('./router.js').then(m => m.renderActive());
}

export function getLangData() { return _current; }
export function getLangMeta(code) { return { flag: LANGS[code]?.flag, name: LANGS[code]?.name }; }
export function getAllLangs() { return LANGS; }

function applyToDOM() {
  // Update any static elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}
